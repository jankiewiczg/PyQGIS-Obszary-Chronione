from qgis.core import (
            Qgis, QgsProject, QgsVectorLayer, QgsFeatureRequest,
            QgsDataSourceUri, QgsFeature, QgsGeometry,
            QgsCoordinateReferenceSystem, QgsCoordinateTransform,
            QgsField, QgsVectorDataProvider
        )
